/**
 * Updates head metadata and document.title per route.
 * @param {string} path - current path like '/', '/faq', etc.
 * @param {boolean} isDashboard - whether currently displaying private dashboard results
 */
export function applyRouteMeta(path, isDashboard = false) {
  if (typeof document === 'undefined') return;

  const targetPath = isDashboard || path === '/dashboard' || path === '/results' ? '/dashboard' : path;
  const meta = routeMeta[targetPath] || routeMeta['/'];

  // Update title
  document.title = meta.title;

  const setMetaTag = (selector, attrName, attrValue, content) => {
    let el = document.querySelector(selector);
    if (!el && content) {
      el = document.createElement('meta');
      el.setAttribute(attrName, attrValue);
      document.head.appendChild(el);
    }
    if (el) {
      if (content) {
        el.setAttribute('content', content);
      } else {
        el.remove();
      }
    }
  };

  // Meta Description
  setMetaTag('meta[name="description"]', 'name', 'description', meta.description);

  // Meta Robots
  setMetaTag('meta[name="robots"]', 'name', 'robots', meta.robots);

  // Open Graph
  setMetaTag('meta[property="og:title"]', 'property', 'og:title', meta.ogTitle);
  setMetaTag('meta[property="og:description"]', 'property', 'og:description', meta.ogDescription);
  setMetaTag('meta[property="og:url"]', 'property', 'og:url', meta.ogUrl);

  // Twitter
  setMetaTag('meta[name="twitter:title"]', 'name', 'twitter:title', meta.ogTitle);
  setMetaTag('meta[name="twitter:description"]', 'name', 'twitter:description', meta.ogDescription);

  // Canonical Link: Set for public routes; remove for dashboard/results
  let canonicalEl = document.querySelector('link[rel="canonical"]');
  if (meta.canonical) {
    if (!canonicalEl) {
      canonicalEl = document.createElement('link');
      canonicalEl.setAttribute('rel', 'canonical');
      document.head.appendChild(canonicalEl);
    }
    canonicalEl.setAttribute('href', meta.canonical);
  } else if (canonicalEl) {
    canonicalEl.remove();
  }
}
